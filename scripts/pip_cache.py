"""Warm the persistent pip cache or prepare updated versions for manual review."""
from __future__ import annotations

import argparse
import importlib.metadata
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path('/repo')
DEPS = Path('/deps')
CUDA_INDEX = 'https://download.pytorch.org/whl/cu128'


def pip(*arguments: str, capture: bool = False) -> str:
    result = subprocess.run(
        [sys.executable, '-m', 'pip', '--disable-pip-version-check', *arguments],
        check=True, text=True, stdout=subprocess.PIPE if capture else None,
    )
    return result.stdout or ''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=('Prepare', 'Update'), default='Prepare', nargs='?')
    mode = parser.parse_args().mode
    DEPS.mkdir(parents=True, exist_ok=True)
    os.environ.setdefault('PIP_CACHE_DIR', str(DEPS / 'pip-cache'))
    if mode == 'Prepare':
        pip('install', '--only-binary=:all:', '-r', str(ROOT / 'pseudonymizer/requirements.txt'))
        pip('check')
        print('Pip cache warmed. The service uses this same cache at startup.')
        return

    inputs = ROOT / 'pseudonymizer/requirements.in'
    torch_bounds = next((line.strip() for line in inputs.read_text().splitlines()
                         if re.match(r'^torch\s*[<>=!~]', line)), None)
    if not torch_bounds:
        raise ValueError('requirements.in must specify torch version bounds')
    # Select the CUDA build first; PyPI may offer a newer build for another CUDA version.
    pip('install', '--upgrade', '--no-deps', '--only-binary=:all:',
        '--index-url', CUDA_INDEX, torch_bounds)
    version = importlib.metadata.version('torch')
    if not version.endswith('+cu128'):
        raise ValueError(f'Expected a CUDA 12.8 PyTorch build; got {version}')
    with tempfile.TemporaryDirectory() as temp:
        constraint = Path(temp) / 'torch.txt'
        constraint.write_text(f'torch=={version}\n')
        pip('install', '--upgrade', '--only-binary=:all:', '-r', str(inputs), '-c', str(constraint))
    pip('check')
    frozen = pip('freeze', capture=True)
    target = DEPS / 'requirements.updated.txt'
    temporary = target.with_suffix('.txt.partial')
    temporary.write_text(f'# Candidate for manual review; generated by pip freeze.\n'
                         f'--extra-index-url {CUDA_INDEX}\n{frozen}', encoding='utf-8')
    temporary.replace(target)
    print(f'Updated versions: {target}. Review before copying to pseudonymizer/requirements.txt.')


if __name__ == '__main__':
    main()
