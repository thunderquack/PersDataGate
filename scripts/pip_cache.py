"""Warm the persistent pip cache or prepare updated versions for manual review."""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path('/repo')
DEPS = Path('/deps')


def pip(*arguments: str, capture: bool = False) -> str:
    result = subprocess.run(
        [sys.executable, '-m', 'pip', '--disable-pip-version-check', *arguments],
        check=True, text=True, stdout=subprocess.PIPE if capture else None,
    )
    return result.stdout or ''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=('Prepare', 'Update'), default='Prepare', nargs='?')
    mode = parser.parse_args().mode
    DEPS.mkdir(parents=True, exist_ok=True)
    os.environ.setdefault('PIP_CACHE_DIR', str(DEPS / 'pip-cache'))
    sys.path.insert(0, str(ROOT))
    from pseudonymizer.dependencies import install_dependencies
    if mode == 'Prepare':
        install_dependencies(ROOT / 'pseudonymizer/requirements.txt')
        pip('check')
        print('Pip cache warmed. The service uses this same cache at startup.')
        return

    inputs = ROOT / 'pseudonymizer/requirements.in'
    install_dependencies(inputs, upgrade=True)
    pip('check')
    frozen = pip('freeze', capture=True)
    target = DEPS / 'requirements.updated.txt'
    temporary = target.with_suffix('.txt.partial')
    temporary.write_text(f'# Candidate for manual review; generated by pip freeze.\n'
                         f'{frozen}', encoding='utf-8')
    temporary.replace(target)
    print(f'Updated versions: {target}. Review before copying to pseudonymizer/requirements.txt.')


if __name__ == '__main__':
    main()
